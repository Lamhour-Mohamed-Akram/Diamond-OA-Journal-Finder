  function setLang(l, opts){
    if (!LANGS.includes(l)) l = 'en';
    lang = l;
    try{ localStorage.setItem('lang', l); }catch(e){}
    if (!(opts && opts.silentUrl)) {
      const u = new URL(location.href);
      if (l === 'en') u.searchParams.delete('lang'); else u.searchParams.set('lang', l);
      history.replaceState(null, '', u.toString());
    }
    apply();
    hooks.forEach(fn => { try{ fn(l); }catch(e){ console.error(e); } });
    window.dispatchEvent(new CustomEvent('i18n:change', { detail: l }));
  }
  function detect(){
    const q = new URLSearchParams(location.search).get('lang');
    if (q && LANGS.includes(q)) return q;
    try{ const s = localStorage.getItem('lang'); if (s && LANGS.includes(s)) return s; }catch(e){}
    const nl = (navigator.language || '').toLowerCase().slice(0, 2);
    return LANGS.includes(nl) ? nl : 'en';
  }
